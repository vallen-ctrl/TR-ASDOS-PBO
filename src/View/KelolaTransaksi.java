    private LocalDate toLocalDate(Date date) {
        return date == null ? null : new java.sql.Date(date.getTime()).toLocalDate();
    }

    private Date toDate(LocalDate localDate) {
        return localDate == null ? null : java.sql.Date.valueOf(localDate);
    }

    private BigDecimal parseRupiah(String input) {
        if (input == null || input.trim().isEmpty()) {
            throw new NumberFormatException("Biaya kerusakan belum diisi.");
        }
        String nilai = input.trim().replaceAll("(?i)rp", "").replaceAll("\\s", "");
        if (nilai.contains(",")) {
            nilai = nilai.replace(".", "").replace(',', '.');
        } else {
            nilai = nilai.replace(".", "");
        }
        nilai = nilai.replaceAll("[^0-9.-]", "");
        if (nilai.isEmpty() || "-".equals(nilai)) {
            throw new NumberFormatException("Format biaya kerusakan tidak valid.");
        }
        BigDecimal hasil = new BigDecimal(nilai).setScale(2, RoundingMode.HALF_UP);
        if (hasil.compareTo(BigDecimal.ZERO) < 0) {
            throw new NumberFormatException("Biaya kerusakan tidak boleh negatif.");
        }
        return hasil;
    }
    private BigDecimal jumlahKerusakanSementara() {
        BigDecimal jumlah = BigDecimal.ZERO;
        for (DamageInput item : daftarKerusakanSementara) {
            jumlah = jumlah.add(item.biaya);
        }
        return jumlah.setScale(2, RoundingMode.HALF_UP);
    }

    private void hitungTotalPengembalian() {
        String kode = txtKodetransaksi.getText().trim();
        if (kode.isEmpty()) {
            txtTotalSewa.setText("");
            txtDendaTerlambat.setText("");
            txtHargaTotal.setText("");
            return;
        }
        try {
            TransaksiData t = getController().getByKode(kode);
            if (t == null) {
                txtTotalSewa.setText("-");
                txtDendaTerlambat.setText("-");
                txtHargaTotal.setText("Kode tidak ditemukan");
                return;
            }
            if (!STATUS_DISEWA.equals(t.status)) {
                txtTotalSewa.setText(formatRupiah(t.total_sewa));
                txtDendaTerlambat.setText("-");
                txtHargaTotal.setText("Transaksi belum berstatus disewa");
                return;
            }
             List<DamageInput> sementara = new ArrayList<>(daftarKerusakanSementara);
            String deskripsiSaatIni = txtDeskripsiKerusakan.getText().trim();
            String biayaSaatIni = txtDendaKerusakan.getText().trim();
            if (!deskripsiSaatIni.isEmpty() && !biayaSaatIni.isEmpty()) {
                try {
                    sementara.add(new DamageInput(deskripsiSaatIni, parseRupiah(biayaSaatIni)));
                } catch (IllegalArgumentException ignored) {
                }
            }

            ReturnCalculation hasil = getController().hitungPengembalian(
                    kode, toLocalDate((Date) spnTglKembaliAktual.getValue()), sementara);
            txtTotalSewa.setText(formatRupiah(hasil.totalSewa));
            txtDendaTerlambat.setText(formatRupiah(hasil.biayaTelat));
            txtHargaTotal.setText(formatRupiah(hasil.totalBayar));
        } catch (SQLException | RuntimeException ex) {
            txtHargaTotal.setText("-");
        }
    }
    private void refreshTabel() {
        DefaultTableModel tabel = new DefaultTableModel(
                new Object[][]{},
                new String[]{"No", "Kode Transaksi", "Pelanggan", "Kendaraan", "Tgl Sewa",
                    "Tgl Kembali", "Status Pengembalian", "Total Harga"}) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        TabRiwayat.setModel(tabel);
        try {
            List<TransaksiData> daftar = getController().getRiwayatTransaksi();
            int nomor = 1;
            for (TransaksiData t : daftar) {
                String status = t.status;
                if (STATUS_SELESAI.equals(t.status) && t.hari_telat > 0) {
                    status += " (Telat " + t.hari_telat + " hari)";
                }
                tabel.addRow(new Object[]{
                    nomor++,
                    t.kode_transaksi,
                    t.nama_pelanggan,
                    t.kendaraan,
                    t.tgl_sewa == null ? "-" : sdf.format(toDate(t.tgl_sewa)),
                    t.tgl_kembali_rencana == null ? "-" : sdf.format(toDate(t.tgl_kembali_rencana)),
                    status,
                    formatRupiah(t.total_bayar)
                });
            }
            } catch (SQLException | RuntimeException ex) {
            tampilkanError("Gagal memuat riwayat transaksi", ex);
        }
    }

    private void refreshTabelKerusakan() {
        DefaultTableModel tabel = new DefaultTableModel(
                new Object[][]{},
                new String[]{"No", "Kode Transaksi", "Pelanggan", "Kendaraan",
                    "Biaya Kerusakan", "Total Harga", "Deskripsi Kerusakan"}) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tabelKerusakan.setModel(tabel);
        try {
            int nomor = 1;
            for (KerusakanData d : getController().getDetailKerusakan()) {
                tabel.addRow(new Object[]{nomor++, d.kodeTransaksi, d.namaPelanggan,
                    d.kendaraan, formatRupiah(d.biaya), formatRupiah(d.totalBayar), d.deskripsi});
            }
            
            String kode = txtKodetransaksi.getText().trim();
            if (!kode.isEmpty() && !daftarKerusakanSementara.isEmpty()) {
                TransaksiData t = getController().getByKode(kode);
                if (t != null) {
                    ReturnCalculation perhitungan = getController().hitungPengembalian(
                            kode, toLocalDate((Date) spnTglKembaliAktual.getValue()),
                            daftarKerusakanSementara);
                    BigDecimal totalAkhir = perhitungan.totalBayar;
                    for (DamageInput d : daftarKerusakanSementara) {
                        tabel.addRow(new Object[]{nomor++, t.kode_transaksi,
                            t.nama_pelanggan, t.kendaraan, formatRupiah(d.biaya),
                            formatRupiah(totalAkhir), d.deskripsi + " (belum disimpan)"});
                    }
                }
            }
        } catch (SQLException | RuntimeException ex) {
        
        }
    }

