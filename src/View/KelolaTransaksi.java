    private void btnBatalBookingRiwayatActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBatalBookingRiwayatActionPerformed
      int baris = TabRiwayat.getSelectedRow();
        if (baris < 0) {
            tampilkanPeringatan("Pilih transaksi pada tabel riwayat terlebih dahulu.");
            return;
        }
        String kode = String.valueOf(TabRiwayat.getValueAt(baris, 1));
        try {
            TransaksiData t = getController().getByKode(kode);
            if (t == null) {
                tampilkanPeringatan("Transaksi tidak ditemukan.");
                return;
            }
            if (!STATUS_DIPESAN.equals(t.status)) {
                tampilkanPeringatan("Hanya transaksi berstatus dipesan yang dapat dibatalkan.");
                return;
            }
            int konfirmasi = JOptionPane.showConfirmDialog(this,
                    "Batalkan booking " + kode + " untuk " + t.nama_pelanggan + "?",
                    "Konfirmasi Pembatalan", JOptionPane.YES_NO_OPTION);
            if (konfirmasi == JOptionPane.YES_OPTION) {
                getController().batalkanBooking(kode);
                refreshTabel();
                muatPelanggan();
                filterKendaraanBerdasarkanJenis();
                JOptionPane.showMessageDialog(this, "Booking berhasil dibatalkan.",
                        "Berhasil", JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (SQLException | RuntimeException ex) {
            tampilkanError("Gagal membatalkan booking", ex);
        }
    }//GEN-LAST:event_btnBatalBookingRiwayatActionPerformed

    private void btnTambahKerusakanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahKerusakanActionPerformed
        // TODO add your handling code here:
        String kondisi = String.valueOf(cmbKondisiKembali.getSelectedItem());
        if (!"Rusak / Tidak Normal".equals(kondisi)) {
            tampilkanPeringatan("Pilih kondisi Rusak / Tidak Normal terlebih dahulu.");
            return;
        }
        String deskripsi = txtDeskripsiKerusakan.getText().trim();
        if (deskripsi.isEmpty()) {
            tampilkanPeringatan("Deskripsi kerusakan wajib diisi.");
            txtDeskripsiKerusakan.requestFocus();
            return;
        }
        try {
            BigDecimal biaya = parseRupiah(txtDendaKerusakan.getText());
            daftarKerusakanSementara.add(new DamageInput(deskripsi, biaya));
            txtDeskripsiKerusakan.setText("");
            txtDendaKerusakan.setText("");
            perbaruiTeksTombolTambahKerusakan();
            hitungTotalPengembalian();
            refreshTabelKerusakan();
            JOptionPane.showMessageDialog(this,
                    "Kerusakan ditambahkan. Jumlah item: " + daftarKerusakanSementara.size()
                    + "\nTotal denda kerusakan: " + formatRupiah(jumlahKerusakanSementara()),
                    "Detail Kerusakan", JOptionPane.INFORMATION_MESSAGE);
        } catch (RuntimeException ex) {
            tampilkanPeringatan(ex.getMessage());
        }
    }//GEN-LAST:event_btnTambahKerusakanActionPerformed

