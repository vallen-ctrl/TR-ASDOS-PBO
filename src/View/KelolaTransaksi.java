    public void setIdKasir(int idKasir) {
        if (idKasir <= 0) {
            throw new IllegalArgumentException("ID kasir harus lebih dari 0.");
        }
        this.idKasir = idKasir;
        if (controller == null) {
            controller = new TransaksiController(idKasir);
        } else {
            controller.setIdKasir(idKasir);
        }
    }

    private int getIdKasirUntukTransaksi() throws SQLException {
        idKasir = getController().getIdKasirUntukTransaksi();
        return idKasir;
    }

    private TransaksiController getController() {
        if (controller == null) {
            controller = new TransaksiController(idKasir);
        }
        return controller;
    }

